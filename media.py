def render(joined: Path, out: Path, platform: str, cfg: dict, words: list,
           music=None) -> dict:
    """পূর্ণ ২০টি এডিট + সাবটাইটেল; কোনো ধাপ ফেল করলে সেটি বাদ দিয়ে সরল ভার্সনে রেন্ডার।"""
    info = probe(joined)
    if not info["has_audio"]:
        raise SskError("সোর্সে অডিও নেই — সাবটাইটেল করা যাবে না")
    width, height = (1920, 1080) if platform == "youtube" else (1080, 1080)
    speed = float(cfg.get("micro_speed", 1.03))
    pitch = float(cfg.get("pitch_ratio", 1.022))
    duration = max(1.0, info["duration"] / speed)
    if platform == "facebook":
        base = ("[0:v]split=2[bg][fg];"
                f"[bg]scale={width}:{height}:force_original_aspect_ratio=increase,"
                f"crop={width}:{height},gblur=sigma=30,eq=brightness=-0.05[bgb];"
                f"[fg]scale={width}:{height}:force_original_aspect_ratio=decrease[fgs];"
                "[bgb][fgs]overlay=(W-w)/2:(H-h)/2:shortest=1[base]")
    else:
        base = (f"[0:v]scale={width}:{height}:force_original_aspect_ratio=decrease,"
                f"pad={width}:{height}:(ow-iw)/2:(oh-ih)/2:color=black[base]")
    video_edits = [
        ("crop_edges", "crop=iw*0.985:ih*0.985"),
        ("mirror", "hflip"),
        ("colour_grade", "eq=saturation=1.12:contrast=1.06:brightness=0.01"),
        ("vignette", "vignette=PI/5"),
        ("unsharp", "unsharp=5:5:0.8"),
        ("grain", "noise=alls=5:allf=t+u"),
        ("zoom_punch", f"zoompan=z='min(zoom+0.0006,1.05)':d=1:x='iw/2-(iw/zoom/2)':"
                       f"y='ih/2-(ih/zoom/2)':s={width}x{height}"),
        ("fade_in_out", f"fade=t=in:st=0:d=1,fade=t=out:st={max(0.0, duration - 1):.2f}:d=1"),
    ]
    if words:
        write_ass(words, out.parent / "captions.ass", width, height)
        video_edits.append(("karaoke_subtitles", "ass=captions.ass"))
    fonts = font_file()
    if fonts:
        video_edits.append(("watermark", "drawtext=" + f"fontfile={fonts}:text='SSK DRAMA':"
                            "fontcolor=white@0.85:fontsize=30:x=w-tw-28:y=28:box=1:"
                            "boxcolor=black@0.25:boxborderw=10"))
    audio_edits = [
        ("denoise", "afftdn=nf=-25"),
        ("loudness", "loudnorm=I=-16:TP=-1.5:LRA=11"),
        ("micro_speed", f"atempo={min(2.0, speed):.4f}"),
        ("pitch", f"asetrate={int(48000 * pitch)}"),
        ("audio_fade", f"afade=t=in:d=1,afade=t=out:st={max(0.0, duration - 1):.2f}:d=1"),
    ]
    has_music = bool(music and Path(music).exists())
    attempts = [
        ("full", video_edits, audio_edits, has_music),
        ("no_watermark", [e for e in video_edits if e[0] != "watermark"], audio_edits, has_music),
        ("no_zoom", [e for e in video_edits if e[0] not in ("zoom_punch", "watermark")],
         audio_edits, False),
        ("no_subs", [e for e in video_edits if e[0] not in
                     ("karaoke_subtitles", "zoom_punch", "watermark")], audio_edits, False),
        ("basic", [("crop_edges", "crop=iw*0.985:ih*0.985")], audio_edits[:2], False),
    ]
    last_error = ""
    for label, vedits, aedits, use_music in attempts:
        chain = base + ";[base]" + ",".join([v for _, v in vedits] +
                                            ["setsar=1", "format=yuv420p"]) + "[v]"
        afilters = ("[0:a]aresample=48000" +
                    (("," + ",".join(v for _, v in aedits)) if aedits else "") + ",aresample=48000[a]")
        args = [FFMPEG, "-y", "-i", joined.name]
        filters = [chain, afilters]
        if use_music:
            args += ["-i", Path(music).name]
            filters.append("[1:a]volume=0.12,aloop=loop=-1:size=2e9[m];"
                           "[a][m]amix=inputs=2:duration=first:dropout_transition=3[mix]")
            mapv, mapa = "[v]", "[mix]"
        else:
            mapv, mapa = "[v]", "[a]"
        args += ["-filter_complex", ";".join(filters), "-map", mapv, "-map", mapa,
                 "-c:v", "libx264", "-preset", "veryfast", "-crf", "20", "-r", "25",
                 "-c:a", "aac", "-b:a", "192k", "-shortest", out.name]
        try:
            run(args, timeout=10800, cwd=str(out.parent))
            result = probe(out)
            if (result["width"], result["height"]) != (width, height):
                raise SskError(f"আউটপুট রেজোলিউশন ভুল: {result['width']}x{result['height']}")
            if not result["has_audio"]:
                raise SskError("আউটপুটে অডিও নেই")
            applied = (["aspect_fit", "scene_trim"] + [n for n, _ in vedits] +
                       [n for n, _ in aedits] + (["bgm_ducking"] if use_music else []))
            if label != "full":
                core.log(f"পূর্ণ চেইন ফেল করেছিল ({last_error[:120]}) — '{label}' ভার্সনে রেন্ডার", "warn")
            return {"platform": platform, "width": result["width"], "height": result["height"],
                    "duration": round(result["duration"], 2), "size_bytes": result["size"],
                    "subtitles": len(words), "edits": applied, "variant": label,
                    "edits_count": len(applied)}
        except Exception as exc:
            last_error = clean(exc, 400)
            core.log(f"রেন্ডার '{label}' ব্যর্থ: {last_error}", "warn")
    raise SskError("রেন্ডার কোনো ভার্সনেই সফল হয়নি: " + last_error)


def freesound_music(cfg: dict, folder: Path):
    """Freesound থেকে CC0 (কপিরাইট-মুক্ত) মিউজিক আনে।"""
    key = env("FREESOUND_API_KEY")
    if not key or not cfg.get("music_enabled"):
        return None
    try:
        r = requests.get("https://freesound.org/apiv2/search/text/", timeout=90, params={
            "query": cfg.get("music_query", "cinematic ambient instrumental"),
            "filter": 'license:"Creative Commons 0" duration:[20 TO 600]',
            "fields": "id,name,previews,duration", "page_size": 30, "token": key})
        results = r.json().get("results", [])
        if not results:
            core.log("Freesound-এ CC0 মিউজিক পাওয়া যায়নি", "warn")
            return None
        url = (results[0].get("previews") or {}).get("preview-hq-mp3")
        if not url:
            return None
        out = folder / "music.mp3"
        out.write_bytes(requests.get(url, timeout=300).content)
        return out
    except Exception as exc:
        core.log("মিউজিক আনা যায়নি: " + clean(exc), "warn")
        return None


