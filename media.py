YT_API = "https://www.googleapis.com/youtube/v3"


def _api_key() -> str:
    return env("YOUTUBE_API_KEY") or env("YT_API_KEY")


def _api(path: str, params: dict) -> dict:
    key = _api_key()
    if not key:
        raise SskError("YOUTUBE_API_KEY নেই — তালিকা বের করা যাবে না")
    q = dict(params)
    q["key"] = key
    r = requests.get(f"{YT_API}/{path}", params=q, timeout=60)
    if r.status_code != 200:
        raise SskError(f"YouTube API {path} {r.status_code}: {clean(r.text, 200)}")
    return r.json()


def iso_seconds(text) -> float:
    m = re.match(r"P(?:(\d+)D)?T?(?:(\d+)H)?(?:(\d+)M)?(?:(\d+(?:\.\d+)?)S)?", str(text or ""))
    if not m:
        return 0.0
    d, h, mi, s = (float(x) if x else 0.0 for x in m.groups())
    return d * 86400 + h * 3600 + mi * 60 + s


def stamp_epoch(text):
    if not text:
        return None
    try:
        from datetime import datetime
        return datetime.fromisoformat(str(text).replace("Z", "+00:00")).timestamp()
    except Exception:
        return None


def handle_of(url):
    """(kind, value) — kind: id | handle | search"""
    u = str(url or "").strip().rstrip("/")
    if "/channel/" in u:
        return "id", u.split("/channel/")[-1].split("/")[0]
    if "/@" in u:
        return "handle", u.split("/@")[-1].split("/")[0]
    if u.startswith("@"):
        return "handle", u[1:].split("/")[0]
    if re.fullmatch(r"UC[\w-]{20,}", u):
        return "id", u
    return "search", (u.split("/")[-1] or u)


def api_channel_entries(url, limit: int = 15) -> list:
    """YouTube Data API দিয়ে চ্যানেলের ভিডিও (duration + তারিখ সহ) — কুকি লাগে না।"""
    kind, value = handle_of(url)
    info = {}
    if kind == "id":
        info = _api("channels", {"part": "contentDetails,snippet", "id": value})
    else:
        if kind == "handle":
            info = _api("channels", {"part": "contentDetails,snippet", "forHandle": value})
        if not info.get("items"):
            info = _api("channels", {"part": "contentDetails,snippet", "forUsername": value})
        if not info.get("items"):
            s = _api("search", {"part": "snippet", "type": "channel", "maxResults": 1, "q": value})
            cid = ((s.get("items") or [{}])[0].get("id", {}) or {}).get("channelId")
            info = _api("channels", {"part": "contentDetails,snippet", "id": cid}) if cid else {}
    if not info.get("items"):
        return []
    uploads = (((info["items"][0].get("contentDetails") or {}).get("relatedPlaylists")) or {}).get("uploads")
    if not uploads:
        return []
    want = max(1, min(400, int(limit)))
    ids, stamps, token = [], {}, None
    while len(ids) < want:
        params = {"part": "contentDetails,snippet", "playlistId": uploads, "maxResults": 50}
        if token:
            params["pageToken"] = token
        pl = _api("playlistItems", params)
        for it in pl.get("items") or []:
            cd = it.get("contentDetails") or {}
            vid = cd.get("videoId") or ((it.get("snippet") or {}).get("resourceId") or {}).get("videoId")
            if not vid or vid in stamps:
                continue
            ids.append(vid)
            stamps[vid] = (it.get("snippet") or {}).get("publishedAt")
        token = pl.get("nextPageToken")
        if not token:
            break
    if not ids:
        return []
    out = []
    for i in range(0, len(ids), 50):
        vr = _api("videos", {"part": "snippet,contentDetails,statistics",
                             "id": ",".join(ids[i:i + 50])})
        for v in vr.get("items") or []:
            sn, cd, st = v.get("snippet") or {}, v.get("contentDetails") or {}, v.get("statistics") or {}
            out.append({"id": v.get("id"), "title": sn.get("title") or "",
                        "duration": iso_seconds(cd.get("duration")),
                        "timestamp": stamp_epoch(sn.get("publishedAt") or stamps.get(v.get("id"))),
                        "view_count": int(st.get("viewCount") or 0),
                        "channel": sn.get("channelTitle") or value})
    return out


def scan_channel(url: str, limit: int = 15, cookies: str = "", deep: int = 0) -> list:
    """তালিকা — প্রথমে YouTube Data API (কুকি লাগে না), না পেলে yt-dlp।

    আগে উল্টো ছিল; কুকি/ক্রেডেনশিয়াল পুরোনো হলে প্রতিটি চ্যানেলে মিনিটের পর মিনিট
    আটকে থাকত — সেটাই "preparing" হয়ে ঘণ্টা পার করিয়ে দিত।
    """
    target = str(url).split("?")[0].rstrip("/")
    if not target.endswith("/videos"):
        target += "/videos"
    entries = []
    try:
        entries = api_channel_entries(str(url), int(deep or max(int(limit), 150)))
        if entries:
            core.log(f"YouTube API দিয়ে তালিকা ({target}) — {len(entries)}টি")
    except Exception as exc:
        core.log(f"YouTube API তালিকা ব্যর্থ ({target}): {clean(exc, 160)}", "warn")
    if not entries:
        try:
            yt_dlp = ensure_ytdlp()
            opts = {"quiet": True, "no_warnings": True, "skip_download": True, "ignoreerrors": True,
                    "extract_flat": False, "playlistend": int(limit), "socket_timeout": 25,
                    "extractor_args": {"youtube": {"player_client": ["web", "tv"]}}}
            if cookies:
                opts["cookiefile"] = str(write_cookies(cookies, Path(core.WORK) / "cookies.txt"))
            with yt_dlp.YoutubeDL(opts) as ydl:
                info = ydl.extract_info(target, download=False)
            entries = [e for e in ((info or {}).get("entries") or []) if e and e.get("id")]
        except Exception as exc:
            core.log(f"yt-dlp তালিকা ব্যর্থ ({target}): {clean(exc, 160)}", "warn")
            entries = []
    return entries


def pick_source(cfg: dict, platform: str, slot: int) -> dict:
    """ফিল্টার মেনে (বয়স ≥ day_filter, ৬০s–৮০মিনিট) সেরা সোর্স বেছে দেয়।"""
    channels = clean_channels(cfg, platform)
    if not channels:
        raise SskError(f"{platform}-এর চ্যানেল সেট করা নেই")
    own = channel_for_slot(cfg, platform, slot)
    order = [own] + [c for c in channels if c != own]
    used = core.history_sources(platform) | {j.get("source_id") for j in core.jobs().values()
                                             if j.get("platform") == platform}
    day = 0 if cfg.get("allow_any_age") else int(cfg.get("day_filter", 60))
    cap = float(cfg.get("max_duration_minutes", 80)) * 60
    floor = float(cfg.get("min_duration_seconds", 60))
    notes, picks = [], []
    why = {"young": 0, "long": 0, "short": 0, "nometa": 0, "used": 0}
    for channel in order:
        try:
            entries = scan_channel(channel, int(cfg.get("metadata_probe_limit", 15)),
                                  env("YT_COOKIES"), deep=int(cfg.get("api_scan_limit", 300)))
        except Exception as exc:
            notes.append(f"{channel}: {clean(exc, 120)}")
            continue
        if not entries:
            notes.append(f"{channel}: তালিকা খালি")
            continue
        for e in entries:
            vid = e.get("id")
            if not vid or vid in used:
                why["used"] += 1
                continue
            dur = float(e.get("duration") or 0)
            stamp = e.get("timestamp") or e.get("release_timestamp")
            age = (time.time() - float(stamp)) / 86400 if stamp else None
            if age is None:
                why["nometa"] += 1
                if day:
                    continue
            elif age < day:
                why["young"] += 1
                continue
            if dur and dur < floor:
                why["short"] += 1
                continue
            if dur and dur > cap and not cfg.get("trim_long_sources"):
                why["long"] += 1
                continue
            picks.append({"url": f"https://www.youtube.com/watch?v={vid}", "id": vid,
                          "title": e.get("title") or "", "duration": dur,
                          "age_days": round(age or 0, 1), "views": e.get("view_count") or 0,
                          "channel": channel, "trim_to": cap if (dur and dur > cap) else 0})
    if notes:
        core.log("স্ক্যান সতর্কতা: " + " | ".join(notes[:2]), "warn")
    if not picks:
        raise SskError(f"{platform} slot {slot + 1}: ব্যবহারযোগ্য ভিডিও নেই "
                       f"(বয়স {day or 'যেকোনো'} দিন, ক্যাপ {int(cap // 60)} মিনিট) — "
                       f"কম পুরোনো {why['young']}, বেশি লম্বা {why['long']}, খাটো {why['short']}, "
                       f"তারিখ নেই {why['nometa']}, আগেই ব্যবহৃত {why['used']}")
    picks.sort(key=lambda x: (x["age_days"], -x["views"]))
    return picks[0]


