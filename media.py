def run(args, timeout=7200, cwd=None):
    p = subprocess.run(args, capture_output=True, text=True, timeout=timeout, cwd=cwd)
    if p.returncode != 0:
        raise SskError("ffmpeg ব্যর্থ: " + clean(p.stderr[-700:], 500))
    return p


def probe(path) -> dict:
    p = subprocess.run([FFPROBE, "-v", "error", "-print_format", "json", "-show_format",
                        "-show_streams", str(path)], capture_output=True, text=True, timeout=300)
    if p.returncode != 0:
        raise SskError("ffprobe ব্যর্থ: " + clean(p.stderr, 200))
    j = json.loads(p.stdout or "{}")
    v = next((s for s in j.get("streams", []) if s.get("codec_type") == "video"), {})
    a = next((s for s in j.get("streams", []) if s.get("codec_type") == "audio"), {})
    return {"duration": float(j.get("format", {}).get("duration") or 0),
            "size": int(j.get("format", {}).get("size") or 0),
            "width": int(v.get("width") or 0), "height": int(v.get("height") or 0),
            "has_audio": bool(a)}


def cookie_text(raw: str) -> str:
    """YT_COOKIES সিকারেট পরিষ্কার করে সঠিক Netscape ফাইল বানায়।

    python-এর cookiejar '# Netscape HTTP Cookie File' (হ্যাশ সহ) চায়; নাহলে
    "does not look like a Netscape format cookies file" এরর দিয়ে কুকি লোডই হয় না।
    """
    rows = [ln for ln in str(raw or "").splitlines()
            if len(ln.split("\t")) == 7 and ln.split("\t")[0].strip()]
    return COOKIE_HEADER + "".join(ln if ln.endswith("\n") else ln + "\n" for ln in rows)


def write_cookies(raw: str, dest: Path) -> Path:
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(cookie_text(raw), encoding="utf-8")
    return dest


