def scene_cuts(path: Path, threshold: float = 0.25) -> list:
    """দৃশ্য পরিবর্তনের সময় (ffmpeg showinfo সরাসরি stderr-এ দেয় — নির্ভরযোগ্য)।"""
    p = subprocess.run([FFMPEG, "-v", "info", "-i", str(path), "-an",
                        "-filter:v", f"select='gt(scene,{threshold})',showinfo",
                        "-f", "null", "-"], capture_output=True, text=True, timeout=5400)
    cuts = []
    for line in (p.stderr or "").splitlines():
        if " n:" in line and "pts_time:" in line:
            found = re.search(r"pts_time:([0-9.]+)", line)
            if found:
                cuts.append(float(found.group(1)))
    return sorted(c for c in cuts if c > 3)


def choose_keeps(duration: float, cuts: list, keep_ratio: float, min_piece: float = 8.0) -> list:
    """মোট দৈর্ঘ্যের (1 − keep_ratio) অংশ বাদ দেয়; দৃশ্য-কাট না পেলে সমান ভাগে কাটে।"""
    target = max(0.0, duration * (1.0 - keep_ratio))
    edges = [0.0] + [c for c in cuts if min_piece < c < duration - min_piece] + [duration]
    pieces = [(edges[i], edges[i + 1]) for i in range(len(edges) - 1)
              if edges[i + 1] - edges[i] >= min_piece]
    if target <= 0:
        return [(0.0, duration)]
    if len(pieces) < 4:
        n = max(8, int(round(duration / 45)) * 2)
        step = duration / n
        pieces = [(i * step, (i + 1) * step) for i in range(n)]
        core.log(f"scene cut কম ({len(cuts)}টি) — সমান {n} ভাগে কাটা হচ্ছে", "warn")
    removed, acc = set(), 0.0
    for i in sorted(range(1, len(pieces) - 1), key=lambda k: -(pieces[k][1] - pieces[k][0])):
        if acc >= target:
            break
        removed.add(i)
        acc += pieces[i][1] - pieces[i][0]
    return [p for i, p in enumerate(pieces) if i not in removed]


def trim_video(path: Path, keeps: list, folder: Path) -> Path:
    if len(keeps) == 1 and keeps[0][0] <= 0.01:
        return path
    parts = []
    for i, (a, b) in enumerate(keeps):
        part = folder / f"part-{i:03d}.mp4"
        run([FFMPEG, "-y", "-ss", f"{a:.3f}", "-to", f"{b:.3f}", "-i", str(path),
             "-c:v", "libx264", "-preset", "veryfast", "-crf", "20",
             "-c:a", "aac", "-b:a", "160k", "-avoid_negative_ts", "make_zero", str(part)], timeout=5400)
        parts.append(part)
    (folder / "concat.txt").write_text("".join(f"file '{p.name}'\n" for p in parts), encoding="utf-8")
    joined = folder / "joined.mp4"
    run([FFMPEG, "-y", "-f", "concat", "-safe", "0", "-i", "concat.txt", "-c", "copy", "joined.mp4"],
        cwd=str(folder))
    return joined


def speed_video(path: Path, factor: float) -> Path:
    factor = max(1.0, min(2.0, factor))
    if factor <= 1.001:
        return path
    out = path.with_name("fast.mp4")
    run([FFMPEG, "-y", "-i", str(path), "-filter_complex",
         f"[0:v]setpts=PTS/{factor:.6f}[v];[0:a]atempo={factor:.6f}[a]",
         "-map", "[v]", "-map", "[a]", "-c:v", "libx264", "-preset", "veryfast", "-crf", "21",
         "-c:a", "aac", "-b:a", "160k", str(out)], timeout=7200)
    return out


def cap_length(path: Path, limit_seconds: float) -> Path:
    info = probe(path)
    if not limit_seconds or info["duration"] <= limit_seconds:
        return path
    return speed_video(path, info["duration"] / limit_seconds)


def transcribe(audio: Path, model_name: str, out_json: Path) -> list:
    """Whisper দিয়ে শব্দ-টাইমিং সহ ট্রান্সক্রিপ্ট (ফাইল থাকলে ক্যাশ থেকে)।"""
    if out_json.exists():
        return json.loads(out_json.read_text(encoding="utf-8")).get("words", [])
    import whisper
    model = whisper.load_model(model_name)
    result = model.transcribe(str(audio), word_timestamps=True, verbose=False)
    words = [{"start": w["start"], "end": w["end"], "text": w["word"]}
             for seg in result.get("segments", []) for w in seg.get("words", [])]
    out_json.write_text(json.dumps({"words": words}, ensure_ascii=False), encoding="utf-8")
    return words


# ----------------------------------------------------------------- subtitles
PALETTE = ["&H0000E5FF&", "&H0059FF59&", "&H00FFD659&", "&H00FF5FD6&", "&H00FFFFFF&",
           "&H00B0B0FF&", "&H00FF9A3C&"]


def ass_time(t: float) -> str:
    t = max(0.0, t)
    h, rem = divmod(t, 3600)
    m, s = divmod(rem, 60)
    return f"{int(h):d}:{int(m):02d}:{s:05.2f}"


def write_ass(words: list, out: Path, width: int, height: int) -> int:
    """রঙিন karaoke সাবটাইটেল (\\kf + ঘুরতে থাকা প্যালেট রং)।"""
    size = 46 if height >= width else 42
    margin = 64 if height >= width else 135
    header = f"""[Script Info]
ScriptType: v4.00+
PlayResX: {width}
PlayResY: {height}
WrapStyle: 2
ScaledBorderAndShadow: yes
[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: K,{BANGLA_FONT},{size},&H0000E5FF&,&H00FFFFFF&,&H00101010&,&H64000000&,-1,0,0,0,100,100,0,0,1,3,1,2,40,40,{margin},1
[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""
    groups, cur = [], []
    for w in words:
        text = str(w.get("text", "")).strip()
        if not text:
            continue
        if cur and (len(cur) >= 5 or w["start"] - cur[-1]["end"] > 0.75
                    or w["end"] - cur[0]["start"] > 3.4):
            groups.append(cur)
            cur = []
        cur.append({**w, "text": text})
    if cur:
        groups.append(cur)
    lines = []
    for gi, group in enumerate(groups):
        start, end, prev, chunks = group[0]["start"], group[-1]["end"], group[0]["start"], []
        for i, w in enumerate(group):
            span = max(6, int(round((w["end"] - prev) * 100)))
            prev = max(prev, w["end"])
            txt = re.sub(r"([\\{}$])", r"\\\1", w["text"])
            chunks.append("{\\kf%d\\1c%s}%s" % (span, PALETTE[(gi * 3 + i) % len(PALETTE)], txt))
        lines.append("Dialogue: 0,%s,%s,K,,0,0,0,,{\\fad(70,70)}%s"
                     % (ass_time(start), ass_time(end + 0.25), " ".join(chunks)))
    out.write_text(header + "\n".join(lines) + "\n", encoding="utf-8")
    return len(groups)


